// Turns a quality-scan.mjs `--format=units` dump into docs/notes/quality-checklist.md.
//
//   node <scanner> crates --root=. --format=units > units.json
//   node scripts/quality-checklist.mjs units.json
import { existsSync, readFileSync, writeFileSync } from "node:fs";

// A Windows path, because the harness runs a bash tool call through cmd.exe
// and hands the argument to a Windows node. The Git Bash form `/c/Users/...`
// reaches node as the relative path it looks like, and node resolves it
// against the drive root: a real autopilot run died on
// `Cannot find module 'C:\c\Users\siriu\...'`.
const SCANNER =
  "C:\\Users\\siriu\\.claude\\plugins\\cache\\dod-guard\\quality-guard\\037c77ae9669\\skills\\quality-refactor\\scripts\\quality-scan.mjs";
const OUT = "docs/notes/quality-checklist.md";

// The units dump arrives from a shell redirect, and which encoding that lands in
// is the shell's choice, not ours. Windows PowerShell 5.1's `>` writes UTF-16LE
// with a byte order mark, so reading it as UTF-8 fails on the first character
// with a SyntaxError naming an unexpected token. Sniff the mark instead of
// trusting one encoding, and drop a UTF-8 mark too, since JSON.parse rejects
// that as well.
const readText = (path) => {
  const buf = readFileSync(path);
  if (buf[0] === 0xff && buf[1] === 0xfe) return buf.toString("utf16le").slice(1);
  if (buf[0] === 0xfe && buf[1] === 0xff) return buf.swap16().toString("utf16le").slice(1);
  return buf.toString("utf8").replace(/^\uFEFF/, "");
};

const data = JSON.parse(readText(process.argv[2]));

// The checklist is generated, but its ticked boxes and `- done:` notes are the
// only state that crosses between autopilot iterations. Reading the previous
// file back is what lets an iteration rescan and regenerate instead of editing
// a row by hand. Hand-edited rows were how the list fell out of score order in
// the first place: a split created files the last scan had never seen, and each
// one got appended under its parent rather than sorted in.
const readPriorState = () => {
  const state = new Map();
  if (!existsSync(OUT)) return state;
  let current = null;
  for (const line of readFileSync(OUT, "utf8").split("\n")) {
    const row = /^- \[([ x])\] `([^`]+)`/.exec(line);
    if (row) {
      const [, mark, file] = row;
      current = state.get(file) ?? { done: false, notes: [] };
      current.done ||= mark === "x";
      state.set(file, current);
      continue;
    }
    const note = /^ {2}- (.+)$/.exec(line);
    if (note && current) current.notes.push(note[1]);
    else if (line.startsWith("#")) current = null;
  }
  return state;
};

const prior = readPriorState();

const metric = (unit, rule, pick) => {
  const values = unit.items.filter((i) => i.rule === rule).map((i) => i.metric);
  return values.length ? pick(...values) : 0;
};

const rows = data.units
  .map((unit) => ({
    file: unit.file,
    test: unit.file.includes("-tests/"),
    done: prior.get(unit.file)?.done ?? false,
    notes: prior.get(unit.file)?.notes ?? [],
    err: unit.errors,
    warn: unit.warnings,
    score: unit.errors * 3 + unit.warnings,
    lines: metric(unit, "file-length", Math.max),
    fnMax: metric(unit, "function-length", Math.max),
    cxMax: metric(unit, "complexity", Math.max),
    rules: Object.entries(unit.rules)
      .sort((a, b) => b[1] - a[1])
      .map(([name, count]) => `${name}:${count}`)
      .join(", "),
  }))
  .sort((a, b) => b.score - a.score || a.file.localeCompare(b.file));

const checklist = (rs) =>
  rs
    .flatMap((r) => [
      `- [${r.done ? "x" : " "}] \`${r.file}\` - score ${r.score} (${r.err} error, ${r.warn} warn)`,
      ...r.notes.map((n) => `  - ${n}`),
    ])
    .join("\n");

const table = (rs) =>
  [
    "| # | File | Score | Err | Warn | Lines | Max fn | Max cx | Rules |",
    "|---|---|---|---|---|---|---|---|---|",
    ...rs.map(
      (r, i) =>
        `| ${i + 1} | \`${r.file}\` | ${r.score} | ${r.err} | ${r.warn} | ${r.lines || "-"} | ${r.fnMax || "-"} | ${r.cxMax || "-"} | ${r.rules} |`,
    ),
  ].join("\n");

const prod = rows.filter((r) => !r.test);
const tests = rows.filter((r) => r.test);

// A file the scanner no longer reports has no violations left. Keeping its row
// here is what stops a regeneration from erasing the record of the work.
const scanned = new Set(rows.map((r) => r.file));
const cleared = [...prior]
  .filter(([file]) => !scanned.has(file))
  .map(([file, s]) => ({ file, notes: s.notes }))
  .sort((a, b) => a.file.localeCompare(b.file));

const clearedList = cleared
  .flatMap((r) => [`- [x] \`${r.file}\` - clean`, ...r.notes.map((n) => `  - ${n}`)])
  .join("\n");

const ruleTotals = Object.entries(data.summary.byRule)
  .sort((a, b) => b[1] - a[1])
  .map(([name, count]) => `- ${name}: ${count}`)
  .join("\n");

const doc = `# Quality refactor checklist

Generated by \`quality-scan.mjs\` over \`crates/\`, default profile. ${data.fileCount} files scanned, ${data.summary.total} violations (${data.summary.errors} error, ${data.summary.warnings} warn).

Score is \`errors * 3 + warnings\`. Every list runs by score, highest first. Work it top down. Check a box only after the file rescans clean and \`cargo test --workspace\` still passes.

Regenerating is safe. This script reads the previous checklist back and carries every ticked box and every \`- done:\` note forward by file path. So rescan and regenerate rather than editing a row by hand: a hand-added row lands wherever it was typed, which is how this list used to fall out of order.

Regenerate:

\`\`\`text
node ${SCANNER} crates --root=. --format=units > .quality/units.json
node scripts/quality-checklist.mjs .quality/units.json
\`\`\`

Rescan one file:

\`\`\`text
node ${SCANNER} <path> --root=.
\`\`\`

## Rule totals

${ruleTotals}

## Production files (${prod.length})

${checklist(prod)}

## Test files (${tests.length})

${checklist(tests)}

## Cleared: no violations left (${cleared.length})

${clearedList}

## Detail: production

${table(prod)}

## Detail: tests

${table(tests)}
`;

writeFileSync(OUT, doc);
const carried = rows.filter((r) => r.done).length + cleared.length;
console.log(
  `wrote ${OUT}: ${prod.length} production, ${tests.length} test files, ${carried} done carried forward`,
);
